# Membuat daftar tamu yang diundang makan malam
tamu = ['Tata', 'Jaya', 'Rania', 'Kusuma', 'Zara']

# Menampilkan daftar tamu
print("Daftar tamu makan malam:")

for nama in tamu:
    print(nama)

# Menghitung jumlah tamu yang diundang
print("\nJumlah tamu yang diundang:")
print(f"Saya mengundang {len(tamu)} orang untuk makan malam.")